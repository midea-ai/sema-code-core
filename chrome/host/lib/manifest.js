// 幂等写入原生宿主清单与包装脚本。Chrome 拉起宿主时不带 PATH，包装脚本里写死 node 绝对路径。
// macOS/Linux：清单放 Chrome 的 NativeMessagingHosts 目录，包装脚本是 sh。
// Windows：Chrome 按注册表 HKCU\Software\Google\Chrome\NativeMessagingHosts\<name> 默认值找清单，
// 清单放 ~/.sema/chrome/，包装脚本是 bat。
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { NATIVE_HOST_NAME, extensionIds, semaChromeDir } from './protocol.js'

const WIN32 = process.platform === 'win32'
const WIN_REG_KEY = `HKCU\\Software\\Google\\Chrome\\NativeMessagingHosts\\${NATIVE_HOST_NAME}`

export function manifestDirs() {
  const home = os.homedir()
  switch (process.platform) {
    case 'darwin':
      return [path.join(home, 'Library', 'Application Support', 'Google', 'Chrome', 'NativeMessagingHosts')]
    case 'linux':
      return [path.join(home, '.config', 'google-chrome', 'NativeMessagingHosts')]
    case 'win32':
      return [semaChromeDir()]
    default:
      throw new Error(`platform ${process.platform} is not supported yet`)
  }
}

export function ensureNativeHostInstalled() {
  const dir = semaChromeDir()
  fs.mkdirSync(dir, { recursive: true })

  const hostScript = fileURLToPath(new URL('../native-host.js', import.meta.url))
  const wrapperPath = path.join(dir, WIN32 ? 'native-host.bat' : 'native-host.sh')
  const wrapper = WIN32
    ? [
        '@echo off',
        'rem Sema browser control native host. Generated by bridge.js; edits are overwritten.',
        `"${process.execPath}" "${hostScript}" %*`,
        '',
      ].join('\r\n')
    : [
        '#!/bin/sh',
        '# Sema browser control native host. Generated by bridge.js; edits are overwritten.',
        `exec ${shellQuote(process.execPath)} ${shellQuote(hostScript)} "$@"`,
        '',
      ].join('\n')
  let changed = writeIfChanged(wrapperPath, wrapper, 0o755)

  const manifest = `${JSON.stringify(
    {
      name: NATIVE_HOST_NAME,
      description: 'Sema browser control native host',
      path: wrapperPath,
      type: 'stdio',
      allowed_origins: extensionIds().map((id) => `chrome-extension://${id}/`),
    },
    null,
    2,
  )}\n`
  const manifestPaths = []
  for (const mdir of manifestDirs()) {
    fs.mkdirSync(mdir, { recursive: true })
    const p = path.join(mdir, `${NATIVE_HOST_NAME}.json`)
    changed = writeIfChanged(p, manifest, 0o644) || changed
    manifestPaths.push(p)
  }
  if (WIN32) changed = ensureWinRegistry(manifestPaths[0]) || changed
  return { changed, wrapperPath, manifestPaths }
}

// 注册表默认值指向清单路径；HKCU 不需要管理员。先读现值，相同就不写。
function ensureWinRegistry(manifestPath) {
  if (readWinRegistry() === manifestPath) return false
  execFileSync('reg.exe', ['add', WIN_REG_KEY, '/ve', '/t', 'REG_SZ', '/d', manifestPath, '/f'], { stdio: 'ignore' })
  return true
}

function readWinRegistry() {
  try {
    const out = execFileSync('reg.exe', ['query', WIN_REG_KEY, '/ve'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] })
    // 输出形如 "    (Default)    REG_SZ    C:\Users\x\.sema\chrome\com.sema.chrome.json"，本地化系统下第一列文字不同，按 REG_SZ 切
    const m = out.match(/REG_SZ\s+(.+?)\s*$/m)
    return m ? m[1] : null
  } catch {
    return null // 键不存在
  }
}

function writeIfChanged(file, content, mode) {
  let current = null
  try {
    current = fs.readFileSync(file, 'utf8')
  } catch {
    // 不存在
  }
  if (current === content) {
    fs.chmodSync(file, mode)
    return false
  }
  fs.writeFileSync(file, content, { mode })
  fs.chmodSync(file, mode)
  return true
}

function shellQuote(s) {
  return `'${String(s).replace(/'/g, `'\\''`)}'`
}
